package be.appify.prefab.mongodb.spring.data.mongodb;

import be.appify.prefab.core.spring.data.FullTextCondition;
import be.appify.prefab.core.spring.data.FullTextQueryExecutor;
import be.appify.prefab.core.spring.data.RangeCondition;
import be.appify.prefab.core.util.TypeaheadQuery;
import java.util.List;
import org.springframework.beans.factory.ObjectProvider;
import org.springframework.data.domain.Example;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageRequest;
import org.springframework.data.domain.Pageable;
import org.springframework.data.mongodb.core.MongoOperations;
import org.springframework.data.mongodb.core.query.Criteria;
import org.springframework.data.mongodb.core.query.Query;
import org.springframework.data.mongodb.core.query.TextCriteria;
import org.springframework.data.mongodb.core.query.TextQuery;
import org.springframework.data.support.PageableExecutionUtils;

/**
 * {@link FullTextQueryExecutor} for Spring Data MongoDB. Combines the example criteria, the range criteria and a
 * {@code $text} search on the same {@link Query}. Requires the text index generated by Prefab on the collection,
 * which covers all full-text properties; the matched properties are therefore determined by that index. {@code $text} has no fuzziness, so
 * {@link FullTextCondition#fuzzy()} is ignored and the search stays exact. Results are ordered by the {@code textScore}
 * when the sort asks for {@link FullTextCondition#RELEVANCE} or is empty. A type-ahead condition matches every word
 * of a plain search text, or the last word of a web search text, as a case-insensitive word-start regular expression
 * on the searched properties, because {@code $text} only matches whole words; a single word that is the initials of
 * a value also matches. The remaining web search words use {@code $text}; without them there is no relevance score.
 */
public class MongoFullTextQueryExecutor implements FullTextQueryExecutor {

    private final ObjectProvider<MongoOperations> operations;

    /**
     * Constructs a new MongoFullTextQueryExecutor.
     *
     * @param operations
     *         provider of the MongoDB operations, resolved when a query is executed
     */
    public MongoFullTextQueryExecutor(ObjectProvider<MongoOperations> operations) {
        this.operations = operations;
    }

    @Override
    public <T> Page<T> findAll(
            Example<T> example,
            FullTextCondition fullText,
            List<RangeCondition> ranges,
            Pageable pageable
    ) {
        var mongo = operations.getObject();
        var type = example.getProbeType();
        var typeahead = fullText.typeaheadQuery();
        var textCriteria = typeahead.wholeWords().isBlank() ? null
                : TextCriteria.forDefaultLanguage().matching(typeahead.wholeWords());
        var prefixCriteria = typeahead.prefixes().isEmpty() ? null : prefixCriteria(fullText, typeahead);
        var countQuery = new Query();
        var findQuery = textCriteria != null && fullText.ranksByRelevance(pageable.getSort())
                ? new TextQuery(textCriteria).sortByScore()
                : new Query();
        for (var query : List.of(countQuery, findQuery)) {
            query.addCriteria(examplePlus(example, fullText.isActive() ? prefixCriteria : null));
            MongoRangeQueryExecutor.criteriaByProperty(ranges).forEach(query::addCriteria);
        }
        if (fullText.isActive() && textCriteria != null) {
            countQuery.addCriteria(textCriteria);
            if (!(findQuery instanceof TextQuery)) {
                findQuery.addCriteria(textCriteria);
            }
        }
        var results = mongo.find(findQuery.with(withoutRelevance(pageable)), type);
        return PageableExecutionUtils.getPage(results, pageable, () -> mongo.count(countQuery, type));
    }

    // A query takes only one criteria without a key, so the prefix criteria must be ANDed into the example criteria
    private static Criteria examplePlus(Example<?> example, Criteria prefixCriteria) {
        var exampleCriteria = new Criteria().alike(example);
        return prefixCriteria == null ? exampleCriteria : new Criteria().andOperator(exampleCriteria, prefixCriteria);
    }

    // $text cannot match prefixes, so each prefix is matched as the start of a word in any searched property
    private static Criteria prefixCriteria(FullTextCondition fullText, TypeaheadQuery typeahead) {
        var words = new Criteria().andOperator(typeahead.prefixes().stream()
                .map(prefix -> anyProperty(fullText, "\\b" + prefix))
                .toArray(Criteria[]::new));
        return typeahead.initials()
                .map(initials -> new Criteria().orOperator(words,
                        anyProperty(fullText, TypeaheadQuery.initialsRegex(initials))))
                .orElse(words);
    }

    private static Criteria anyProperty(FullTextCondition fullText, String regex) {
        return new Criteria().orOperator(fullText.properties().stream()
                .map(property -> Criteria.where(property).regex(regex, "i"))
                .toArray(Criteria[]::new));
    }

    private static Pageable withoutRelevance(Pageable pageable) {
        var sort = FullTextCondition.withoutRelevance(pageable.getSort());
        return pageable.isPaged()
                ? PageRequest.of(pageable.getPageNumber(), pageable.getPageSize(), sort)
                : Pageable.unpaged(sort);
    }
}
