package be.appify.prefab.processor.agent;

import be.appify.prefab.core.annotations.Event;
import be.appify.prefab.core.annotations.EventHandler;
import be.appify.prefab.processor.ClassManifest;
import be.appify.prefab.processor.PolymorphicAggregateManifest;
import be.appify.prefab.processor.PrefabContext;
import be.appify.prefab.processor.rest.AggregateEndpoints;
import be.appify.prefab.processor.rest.ControllerUtil;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;
import java.util.Optional;
import java.util.TreeSet;
import java.util.stream.Collectors;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.TypeElement;
import javax.lang.model.type.DeclaredType;
import javax.lang.model.type.TypeMirror;

import static be.appify.prefab.processor.CaseUtil.toSnakeCase;

/**
 * Renders the Markdown for {@link AgentContextPlugin}. Output is deterministic: every collection is sorted and no
 * timestamps or absolute paths are included.
 */
final class AgentContextRenderer {
    private static final List<Capability> CAPABILITIES = List.of(
            new Capability("Postgres persistence", "be.appify.prefab.postgres.spring.PrefabJdbcConfiguration",
                    "Spring Data JDBC repositories; Flyway migrations are generated from the domain model",
                    List.of("spring.datasource.url", "spring.datasource.username", "spring.datasource.password")),
            new Capability("MongoDB persistence", "be.appify.prefab.mongodb.spring.PrefabMongoConfiguration",
                    "Spring Data MongoDB repositories; indexes are generated from the domain model",
                    List.of("spring.data.mongodb.uri")),
            new Capability("Kafka events", "org.springframework.kafka.core.KafkaTemplate",
                    "events are published and consumed through Kafka topics",
                    List.of("spring.kafka.bootstrap-servers")),
            new Capability("Pub/Sub events", "com.google.cloud.spring.pubsub.core.admin.PubSubAdmin",
                    "events are published and consumed through Google Pub/Sub topics",
                    List.of("spring.cloud.gcp.project-id")),
            new Capability("SNS/SQS events", "io.awspring.cloud.sns.core.SnsTemplate",
                    "events are published and consumed through AWS SNS topics and SQS queues",
                    List.of("spring.cloud.aws.region.static", "spring.cloud.aws.credentials.access-key",
                            "spring.cloud.aws.credentials.secret-key")),
            new Capability("Spring Security", "be.appify.prefab.core.security.WebSecurityConfiguration",
                    "`@Security` on endpoints is enforced; generated test clients support `as(...)` overrides",
                    List.of()),
            new Capability("OpenAPI", "be.appify.prefab.openapi.OpenApiAutoConfiguration",
                    "REST documentation is exposed by springdoc", List.of()),
            new Capability("AsyncAPI", "be.appify.prefab.asyncapi.AsyncApiConfiguration",
                    "event documentation is exposed as AsyncAPI", List.of()),
            new Capability("Kafka Streams", "be.appify.prefab.streams.kafka.StreamsConfiguration",
                    "stream processing on Kafka Streams", List.of("spring.kafka.bootstrap-servers"))
    );

    private final PrefabContext context;

    AgentContextRenderer(PrefabContext context) {
        this.context = context;
    }

    String render(List<ClassManifest> manifests, List<PolymorphicAggregateManifest> polymorphicManifests) {
        var active = CAPABILITIES.stream().filter(this::isActive).toList();
        var out = new StringBuilder();
        out.append("# Prefab agent context\n\n")
                .append("Generated by the Prefab annotation processor from this project's classpath and domain ")
                .append("model. Do not edit it and do not edit `target/generated-sources`: change the annotated ")
                .append("domain types instead and recompile.\n\n");
        appendCapabilities(out, active);
        appendAggregates(out, manifests, polymorphicManifests, active);
        appendConformanceTests(out);
        appendEvents(out);
        appendConfiguration(out, active);
        appendLocalVerification(out);
        return out.toString();
    }

    private static void appendConformanceTests(StringBuilder out) {
        out.append("## Generated conformance tests\n\n")
                .append("With `prefab-test` on the test classpath, Prefab generates tests for public endpoint ")
                .append("security (when Spring Security is enabled) and event serialization round-trips. ")
                .append("Opt out per aggregate or event with `conformanceTest = false` on `@Aggregate` or `@Event`.\n\n");
    }

    private boolean isActive(Capability capability) {
        return context.processingEnvironment().getElementUtils().getTypeElement(capability.marker()) != null;
    }

    private void appendCapabilities(StringBuilder out, List<Capability> active) {
        out.append("## Active capabilities\n\n");
        active.forEach(capability -> out.append("- **%s**: %s\n".formatted(capability.name(), capability.hint())));
        out.append("\nCapabilities that are not listed are not on this project's classpath; do not use their ")
                .append("patterns.\n\n");
    }

    private void appendAggregates(
            StringBuilder out,
            List<ClassManifest> manifests,
            List<PolymorphicAggregateManifest> polymorphicManifests,
            List<Capability> active
    ) {
        out.append("## Aggregates\n\n");
        manifests.stream()
                .sorted(Comparator.comparing(ClassManifest::qualifiedName))
                .forEach(manifest -> appendAggregate(out, manifest, active));
        polymorphicManifests.stream()
                .sorted(Comparator.comparing(m -> m.packageName() + "." + m.simpleName()))
                .forEach(manifest -> out.append("### %s (polymorphic, `%s`)\n\n- Base path: `/%s`\n\n".formatted(
                        manifest.simpleName(), manifest.packageName(), ControllerUtil.pathOf(manifest))));
    }

    private void appendAggregate(StringBuilder out, ClassManifest manifest, List<Capability> active) {
        out.append("### %s (`%s`)\n\n".formatted(manifest.simpleName(), manifest.packageName()));
        out.append("- Endpoints:\n");
        endpoints(manifest).forEach(endpoint -> out.append("  - ").append(endpoint).append('\n'));
        handledEvents(manifest).forEach(handled -> out.append("- Handles: ").append(handled).append('\n'));
        persistence(manifest, active).ifPresent(persistence -> out.append("- Persistence: ").append(persistence).append('\n'));
        out.append("- Test helpers: `%sClient` (MockMvc client), generated Mothers and AssertJ assertions\n\n"
                .formatted(manifest.simpleName()));
    }

    private List<String> endpoints(ClassManifest manifest) {
        var lines = AggregateEndpoints.of(manifest).stream()
                .map(endpoint -> endpoint(endpoint.method(), endpoint.path(), endpoint.description()))
                .sorted()
                .distinct()
                .toList();
        return lines.isEmpty() ? List.of("none") : lines;
    }

    private static String endpoint(String method, String path, String description) {
        return "`%s %s` (%s)".formatted(method, path, description);
    }

    private List<String> handledEvents(ClassManifest manifest) {
        return manifest.methodsWith(EventHandler.class).stream()
                .map(this::describeHandler)
                .sorted()
                .toList();
    }

    private String describeHandler(ExecutableElement handler) {
        var parameterType = handler.getParameters().isEmpty() ? null : handler.getParameters().getFirst().asType();
        var eventElement = asTypeElement(parameterType);
        var eventName = eventElement.map(AgentContextRenderer::displayName)
                .orElseGet(() -> parameterType == null ? "unknown" : parameterType.toString());
        var topics = eventElement.map(AgentContextRenderer::topicsOf).orElse("");
        return "`%s` via `%s()`%s".formatted(eventName, handler.getSimpleName(), topics);
    }

    private Optional<TypeElement> asTypeElement(TypeMirror type) {
        if (type instanceof DeclaredType declared && declared.asElement() instanceof TypeElement element) {
            return Optional.of(element);
        }
        return Optional.empty();
    }

    private Optional<String> persistence(ClassManifest manifest, List<Capability> active) {
        var simpleName = manifest.simpleName();
        var names = new ArrayList<String>();
        if (hasCapability(active, "Postgres persistence")) {
            names.add("table `%s`".formatted(toSnakeCase(simpleName)));
        }
        if (hasCapability(active, "MongoDB persistence")) {
            names.add("collection `%s`".formatted(Character.toLowerCase(simpleName.charAt(0)) + simpleName.substring(1)));
        }
        return names.isEmpty() ? Optional.empty() : Optional.of(String.join(", ", names));
    }

    private static boolean hasCapability(List<Capability> active, String name) {
        return active.stream().anyMatch(capability -> capability.name().equals(name));
    }

    private void appendEvents(StringBuilder out) {
        var events = context.eventElementsFromCurrentCompilation()
                .sorted(Comparator.comparing(element -> element.getQualifiedName().toString()))
                .toList();
        if (events.isEmpty()) {
            return;
        }
        out.append("## Events\n\n");
        events.forEach(event -> out.append("- `%s`%s%s\n".formatted(
                displayName(event), topicsOf(event), serializationOf(event))));
        out.append('\n');
    }

    private static String serializationOf(TypeElement event) {
        var avro = Arrays.stream(event.getAnnotationsByType(Event.class))
                .anyMatch(annotation -> annotation.serialization() == Event.Serialization.AVRO);
        return avro ? ", Avro" : "";
    }

    private static String topicsOf(TypeElement event) {
        var topics = Arrays.stream(event.getAnnotationsByType(Event.class))
                .flatMap(annotation -> Arrays.stream(annotation.topic()))
                .collect(Collectors.toCollection(TreeSet::new));
        return topics.isEmpty() ? "" : " on topic " + topics.stream().map("`%s`"::formatted)
                .collect(Collectors.joining(", "));
    }

    private static String displayName(TypeElement element) {
        var name = element.getSimpleName().toString();
        return element.getEnclosingElement() instanceof TypeElement enclosing
                ? displayName(enclosing) + "." + name : name;
    }

    private void appendConfiguration(StringBuilder out, List<Capability> active) {
        var properties = active.stream()
                .flatMap(capability -> capability.properties().stream())
                .collect(Collectors.toCollection(TreeSet::new));
        if (properties.isEmpty()) {
            return;
        }
        out.append("## Required configuration\n\n");
        properties.forEach(property -> out.append("- `%s`\n".formatted(property)));
    }

    private static void appendLocalVerification(StringBuilder out) {
        out.append("## Local verification\n\n")
                .append("When `prefab-test` is a test dependency, run `mvn test-compile spring-boot:test-run` ")
                .append("to start the app on in-memory repositories and an in-process event bus without Docker. ")
                .append("Use the printed base URL and docs links to verify the running app.\n");
    }

    private record Capability(String name, String marker, String hint, List<String> properties) {
    }
}
